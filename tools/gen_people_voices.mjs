// Writes src/audio/peopleVoices.gen.js: one import per recorded clip that data/grownups.json uses,
// so the page only carries the clips the grown-ups actually say.  Run: node tools/gen_people_voices.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const data = JSON.parse(readFileSync('data/grownups.json', 'utf8'));
const files = new Set();
for (const [m, v] of Object.entries(data.models)) if (!m.startsWith('_')) for (const f of Object.values(v.voice)) files.add(f);
const list = [...files].sort();
const out = `// generated by tools/gen_people_voices.mjs from data/grownups.json: the grown-ups' recorded reactions\n${list.map((f, i) => `import c${i} from '../../assets/voices/${f}.mp3';`).join('\n')}\nexport const PEOPLE_VOICES = {\n${list.map((f, i) => `  '${f}': c${i},`).join('\n')}\n};\n`;
writeFileSync('src/audio/peopleVoices.gen.js', out);
console.log(list.length, 'clips');
