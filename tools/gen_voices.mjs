// Writes legacy/js/voicefiles.gen.js: one import per recorded clip in assets/voices.
// Keys:  "<who>:L<n>"  a grown-up's numbered script line      (assets/hf/voice_script.json)
//        "<who>:A<n>"  a grown-up's question                  (same file)
//        "<who>:B<n>"  a grown-up's short reaction            (BARK order in tools/voice_plan.mjs)
//        "kid_top:K<n>", "narrator:N<n>"  kids and narrator   (line order in assets/library/voice_plan.json)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const script = JSON.parse(readFileSync('assets/hf/voice_script.json', 'utf8'));
const have = new Set(readdirSync('assets/voices'));
const imps = [], keys = [];
const add = (file, key) => { if (!have.has(file)) return; const v = `v${imps.length}`; imps.push(`import ${v} from '../assets/voices/${file}';`); keys.push(`  '${key}': ${v},`); };
for (const [id, lines] of Object.entries(script)) lines.forEach((l, n) => {
  if (l.i === undefined && l.ask === undefined) return;      // kids and narrator come from the plan below
  add(`${id}_${n}.mp3`, `${id}:${l.i !== undefined ? 'L' + l.i : 'A' + l.ask}`);
});
for (const f of [...have].sort()) {
  const m = f.match(/^(.+)_([BKN])(\d+)\.mp3$/);
  if (m) add(f, `${m[1]}:${m[2]}${m[3]}`);
}
writeFileSync('legacy/js/voicefiles.gen.js', `// generated by tools/gen_voices.mjs: recorded lines (Higgsfield voices), one small mp3 each\n${imps.join('\n')}\nexport const VOICE_FILES = {\n${keys.join('\n')}\n};\n`);
console.log(keys.length, 'recorded clips');
