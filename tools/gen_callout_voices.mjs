// Writes src/audio/calloutVoices.gen.js: one import per recorded kid and narrator line that
// data/juice.json uses (from the old game's voices), so the page only carries the lines it plays.
// Run: node tools/gen_callout_voices.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const J = JSON.parse(readFileSync('data/juice.json', 'utf8'));
const files = new Set();
for (const list of Object.values(J.kids)) for (const [who, n] of list) files.add(`${who}_K${n}`);
for (const n of Object.values(J.narrator)) files.add(`narrator_N${n}`);
const list = [...files].sort();
const out = `// generated by tools/gen_callout_voices.mjs from data/juice.json: the kids' and the narrator's recorded lines\n${list.map((f, i) => `import v${i} from '../../assets/voices/${f}.mp3';`).join('\n')}\nexport const CALLOUT_VOICES = {\n${list.map((f, i) => `  '${f}': v${i},`).join('\n')}\n};\n`;
writeFileSync('src/audio/calloutVoices.gen.js', out);
console.log(list.length, 'clips');
